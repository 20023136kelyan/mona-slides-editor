// Slices the bundled multi-megabyte CJK fonts into unicode-range banded
// woff2 chunks so browsers fetch only the bands a deck actually renders
// (the Google-Fonts CJK strategy). Outputs:
//   apps/web/src/assets/fonts/sliced/<Family>/<band>.woff2
//   apps/web/src/assets/fonts-sliced.css   (generated @font-face blocks)
//
// Run after adding or updating a CJK source font:
//   node scripts/subset-cjk-fonts.mjs
//
// The flat source woff2 files stay in the repo as slicing input; they live in
// fonts/source/, outside every CSS reference and asset glob, so production
// bundles exclude them.

import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import subsetFont from 'subset-font'

const repositoryRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const fontsRoot = join(repositoryRoot, 'apps/web/src/assets/fonts')
const slicedRoot = join(fontsRoot, 'sliced')
const cssPath = join(repositoryRoot, 'apps/web/src/assets/fonts-sliced.css')

// Every bundled font larger than ~1MB — all CJK faces.
const SLICED_FAMILIES = [
  'AlibabaPuHuiTi',
  'DeYiHei',
  'LXGWNeoXiHei',
  'LXGWNeoZhiSong',
  'LXGWWenKai',
  'MiSans',
  'SourceHanSans',
  'SourceHanSerif',
  'WenDingPLKaiTi',
  'WenDingPLSongTi',
  'ZhuQueFangSong',
]

const range = (start, end) => [start, end]

// Band layout: a base band with everything a deck needs before ideographs
// (Latin, punctuation, kana, fullwidth forms), CJK Unified split into sixteen
// equal bands, then extension/compat bands. The subset text and the CSS
// unicode-range are generated from the SAME table, so they cannot drift.
const BANDS = [
  { name: 'base', ranges: [range(0x0020, 0x2fff), range(0x3000, 0x33ff), range(0xfe30, 0xffef)] },
  { name: 'exta', ranges: [range(0x3400, 0x4dbf)] },
  ...Array.from({ length: 16 }, (_, index) => ({
    name: `cjk-${String(index).padStart(2, '0')}`,
    ranges: [range(0x4e00 + index * 0x520, 0x4e00 + (index + 1) * 0x520 - 1)],
  })),
  { name: 'compat', ranges: [range(0xa000, 0xa4cf), range(0xf900, 0xfaff)] },
  { name: 'extb', ranges: [range(0x20000, 0x2fa1f)] },
]

const bandText = ranges => {
  const parts = []
  for (const [start, end] of ranges) {
    for (let codePoint = start; codePoint <= end; codePoint += 1) {
      // Skip surrogate space; it is not valid text.
      if (codePoint >= 0xd800 && codePoint <= 0xdfff) continue
      parts.push(String.fromCodePoint(codePoint))
    }
  }
  return parts.join('')
}

const cssRange = ranges => ranges
  .map(([start, end]) => `U+${start.toString(16).toUpperCase()}-${end.toString(16).toUpperCase()}`)
  .join(', ')

const css = [
  '/* GENERATED by scripts/subset-cjk-fonts.mjs — do not edit by hand. */',
  '/* Banded unicode-range slices of the bundled CJK fonts: the browser */',
  '/* downloads only the bands whose codepoints a deck actually uses. */',
]

await rm(slicedRoot, { recursive: true, force: true })
let totalBytes = 0
for (const family of SLICED_FAMILIES) {
  const source = await readFile(join(fontsRoot, 'source', `${family}.woff2`))
  await mkdir(join(slicedRoot, family), { recursive: true })
  let familyBytes = 0
  for (const band of BANDS) {
    const subset = await subsetFont(source, bandText(band.ranges), { targetFormat: 'woff2' })
    await writeFile(join(slicedRoot, family, `${band.name}.woff2`), subset)
    familyBytes += subset.length
    css.push(
      '@font-face {',
      '  font-display: swap;',
      `  font-family: ${family};`,
      `  src: url('./fonts/sliced/${family}/${band.name}.woff2') format('woff2');`,
      `  unicode-range: ${cssRange(band.ranges)};`,
      '}',
    )
  }
  totalBytes += familyBytes
  console.log(`${family}: ${(source.length / 1048576).toFixed(1)}MB -> ${BANDS.length} bands, ${(familyBytes / 1048576).toFixed(1)}MB total`)
}
await writeFile(cssPath, `${css.join('\n')}\n`)
console.log(`sliced total on disk: ${(totalBytes / 1048576).toFixed(1)}MB; css: ${cssPath}`)
